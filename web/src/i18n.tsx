export type Lang = "zh" | "en";
export const DICTS: Record<Lang, Record<Key, string>> = { zh, en };
/** 运行时拼出来的键（如 gap.<服务端给的原因>）先确认字典里有 */
export const hasKey = (k: string): k is Key => Object.prototype.hasOwnProperty.call(zh, k);

export function format(s: string, vars?: Record<string, string | number>) {
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

export type T = (k: Key, vars?: Record<string, string | number>) => string;
type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: T };
const LangCtx = createContext<Ctx>({ lang: "zh", setLang: () => {}, t: (k, v) => format(zh[k], v) });
export const useT = () => useContext(LangCtx);

function initialLang(): Lang {
  try {
    const v = localStorage.getItem("sr-lang");
    if (v === "zh" || v === "en") return v;
  } catch {
    /* 隐私模式等读不到存储时用默认 */
  }
  return navigator.language?.toLowerCase().startsWith("en") ? "en" : "zh";
}

function apply(l: Lang) {
  setApiLang(l);
  setTimeLang(l);
  document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
}

export function LangProvider({ children }: { children: (lang: Lang) => ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const l = initialLang();
    apply(l);
    return l;
  });
  const setLang = useCallback((l: Lang) => {
    apply(l);
    try {
      localStorage.setItem("sr-lang", l);
    } catch {
      /* 存不下也不影响本次切换 */
    }
    setLangState(l);
  }, []);
  const t = useCallback<T>((k, vars) => format(DICTS[lang][k], vars), [lang]);
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children(lang)}</LangCtx.Provider>;
}
